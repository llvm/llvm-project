template <class E, typename Arg>
void test_implicit() {
#if TEST_STD_VER >= 11
  static_assert(test_convertible<E>(), "");
  assert(E(E::default_seed) == make_implicit<E>());
  static_assert(!test_convertible<E, Arg>(), "");
#endif
}

