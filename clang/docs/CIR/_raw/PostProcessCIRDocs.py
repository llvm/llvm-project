# This script post-processes the MLIR-generated CIR documentation (in Markdown
# format) for the Sphinx build: it merges the passes reference into
# CIRDialect.md ahead of the other sections, converts the [TOC] marker into
# an index of the page sections, and appends a toctree entry to the build
# directory copy of index.md.

import os
import re
import sys

docs_src_dir = sys.argv[1]
docs_bin_dir = sys.argv[2]

DIALECT_DOC_PATH = os.path.join(docs_bin_dir, "CIR", "_raw", "CIRDialect.md")
PASSES_DOC_PATH = os.path.join(docs_bin_dir, "CIR", "_raw", "CIRPasses.md")
DIALECT_DOC_OUTPUT_PATH = os.path.join(docs_bin_dir, "CIR", "CIRDialect.md")

INDEX_PATH = os.path.join(docs_src_dir, "CIR", "index.md")
INDEX_OUTPUT_PATH = os.path.join(docs_bin_dir, "CIR", "index.md")

cir_docs_toctree = []

# ===============================================
# Post-process CIRDialect.md
# ===============================================
def _slugify(title):
    slug = title.strip().lower()
    slug = re.sub(r"\s+", "-", slug)
    slug = re.sub(r"[^a-z0-9_-]", "", slug)
    return slug


if os.path.exists(DIALECT_DOC_PATH):
    cir_docs_toctree.append("CIRDialect")
    with open(DIALECT_DOC_PATH, encoding="utf-8") as fp:
        dialect_doc = fp.read()
    # Retitle the page: tblgen emits "# 'cir' Dialect" as the top heading.
    dialect_doc = dialect_doc.replace("# 'cir' Dialect", "# CIR Dialect Reference", 1)
    if os.path.exists(PASSES_DOC_PATH):
        with open(PASSES_DOC_PATH, encoding="utf-8") as fp:
            passes_doc = fp.read()
        passes_doc = passes_doc.replace(
            "<!-- Autogenerated by mlir-tblgen; don't manually edit -->\n", ""
        )
        insert = "\n## Passes\n" + passes_doc.strip() + "\n"
        head, sep, rest = dialect_doc.partition("\n## ")
        if sep:
            dialect_doc = head.rstrip("\n") + "\n" + insert + sep + rest
        else:
            dialect_doc = dialect_doc.rstrip("\n") + "\n" + insert
    # Replace the [TOC] marker with an index of the page sections so the
    # (very long) single page stays navigable. Plain <a> links are used
    # instead of [text](#anchor): MyST would treat the latter as
    # cross-references and warn that the targets don't exist.
    # Scan headings outside fenced code blocks so that ``` examples in op
    # descriptions can never contribute bogus index entries.
    doc_no_fences = re.sub(r"```.*?```", "", dialect_doc, flags=re.S)
    sections = re.findall(r"^## (\S.*?)\s*$", doc_no_fences, re.M)
    index = "\n".join(f'- <a href="#{_slugify(t)}">{t}</a>' for t in sections)
    dialect_doc = dialect_doc.replace("[TOC]", index)
    with open(DIALECT_DOC_OUTPUT_PATH, "w", encoding="utf-8") as fp:
        fp.write(dialect_doc)

# ===============================================
# Add CIR Dialect Reference section to index.md if CIR docs are generated
# ===============================================
if len(cir_docs_toctree) > 0:
    with open(INDEX_PATH, encoding="utf-8") as fp:
        index_content = fp.read()
    # Visible index into the reference page sections. Plain <a> links are
    # used instead of [text](page#anchor): MyST would treat the latter as
    # cross-references and warn that the targets don't exist.
    ref_index = "\n".join(
        f'- <a href="{page}.html#{_slugify(t)}">{t}</a>'
        for page in cir_docs_toctree
        for t in sections
    )
    # The toctree entry itself stays (Sphinx requires every document to be
    # in a toctree) but hidden: the index above replaces the visible
    # numbered link.
    new_section = (
        "CIR Dialect Reference\n\n"
        + ref_index
        + "\n\n```{toctree}\n:hidden:\n:maxdepth: 1\n\n"
        + "\n".join(cir_docs_toctree)
        + "\n```\n"
    )
    # Place the section right after "Using ClangIR"; fall back to appending
    # at the end if index.md is ever restructured.
    chunks = index_content.split("\n## ")
    idx = next(
        (
            i
            for i, c in enumerate(chunks)
            if c == "Using ClangIR" or c.startswith("Using ClangIR\n")
        ),
        None,
    )
    if idx is None:
        index_content = index_content.rstrip("\n") + "\n\n## " + new_section
    else:
        chunks.insert(idx + 1, new_section)
        index_content = "\n## ".join(chunks)
    with open(INDEX_OUTPUT_PATH, "w", encoding="utf-8") as fp:
        fp.write(index_content)
