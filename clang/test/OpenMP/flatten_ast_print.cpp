// placeholder for loop body code.
extern "C" void body(...);

// PRINT-LABEL: void foo1(
// DUMP-LABEL:  FunctionDecl {{.*}} foo1
void foo1() {
  // PRINT:     #pragma omp flatten
  // DUMP:      OMPFlattenDirective
  #pragma omp flatten
  // PRINT: for (int i = 0; i < 7; i += 1)
  // DUMP-NEXT: ForStmt
  for (int i = 0; i < 7; i += 1)
    // PRINT: for (int j = 0; j < 9; j += 1)
    // DUMP:  ForStmt
    for (int j = 0; j < 9; j += 1)
      // PRINT: body(i, j);
      // DUMP:  CallExpr
      body(i, j);
}

// PRINT-LABEL: void foo2(
// DUMP-LABEL:  FunctionDecl {{.*}} foo2
void foo2(int start1, int end1, int step1, int start2, int end2, int step2) {
  // PRINT:     #pragma omp flatten
  // DUMP:      OMPFlattenDirective
  #pragma omp flatten
  // PRINT: for (int i = start1; i < end1; i += step1)
  // DUMP-NEXT: ForStmt
  for (int i = start1; i < end1; i += step1)
    // PRINT: for (int j = start2; j < end2; j += step2)
    // DUMP:  ForStmt
    for (int j = start2; j < end2; j += step2)
      // PRINT: body(i, j);
      // DUMP:  CallExpr
      body(i, j);
}

// PRINT-LABEL: void foo3(
// DUMP-LABEL:  FunctionDecl {{.*}} foo3
void foo3() {
  // Verify that a flattened loop can itself be the operand of another loop
  // transformation. The outer reverse consumes the loop generated by flatten.
  // PRINT:     #pragma omp reverse
  // DUMP:      OMPReverseDirective
  #pragma omp reverse
  // PRINT:     #pragma omp flatten
  // DUMP:      OMPFlattenDirective
  #pragma omp flatten
  // PRINT: for (int i = 0; i < 13; i += 1)
  // DUMP-NEXT: ForStmt
  for (int i = 0; i < 13; i += 1)
    // PRINT: for (int j = 0; j < 17; j += 1)
    // DUMP:  ForStmt
    for (int j = 0; j < 17; j += 1)
      // PRINT: body(i, j);
      // DUMP:  CallExpr
      body(i, j);
}

// Range-based for loops are supported as affected loops.
// PRINT-LABEL: void foo4(
// DUMP-LABEL:  FunctionDecl {{.*}} foo4
struct Range {
  int *begin();
  int *end();
};
void foo4(Range r1, Range r2) {
  // PRINT:     #pragma omp flatten
  // DUMP:      OMPFlattenDirective
  #pragma omp flatten
  // PRINT: for (int i : r1)
  // DUMP-NEXT: CXXForRangeStmt
  for (int i : r1)
    // PRINT: for (int j : r2)
    // DUMP:  CXXForRangeStmt
    for (int j : r2)
      // PRINT: body(i, j);
      // DUMP:  CallExpr
      body(i, j);
}

// The directive is instantiated together with its enclosing template.
// PRINT-LABEL: template <typename T, int LO, int HI> void foo5()
// DUMP-LABEL:  FunctionTemplateDecl {{.*}} foo5
template <typename T, int LO, int HI>
void foo5() {
  // PRINT:     #pragma omp flatten
  // DUMP:      OMPFlattenDirective
  #pragma omp flatten
  // PRINT: for (T i = LO; i < HI; ++i)
  // DUMP-NEXT: ForStmt
  for (T i = LO; i < HI; ++i)
    // PRINT: for (T j = LO; j < HI; ++j)
    // DUMP:  ForStmt
    for (T j = LO; j < HI; ++j)
      // PRINT: body(i, j);
      // DUMP:  CallExpr
      body(i, j);
}

// PRINT-LABEL: template<> void foo5<int, 0, 8>()
// DUMP-LABEL:  FunctionDecl {{.*}} foo5 'void ()' implicit_instantiation
// DUMP:        OMPFlattenDirective
void inst() {
  foo5<int, 0, 8>();
}

// Unroll applied to the loop generated by flatten.
// PRINT-LABEL: void foo7(
// DUMP-LABEL:  FunctionDecl {{.*}} foo7
void foo7() {
  // PRINT:     #pragma omp unroll partial(2)
  // DUMP:      OMPUnrollDirective
  #pragma omp unroll partial(2)
  // PRINT:     #pragma omp flatten
  // DUMP:      OMPFlattenDirective
  #pragma omp flatten
  for (int i = 0; i < 4; ++i)
    for (int j = 0; j < 3; ++j)
      body(i, j);
}

// Tile applied to the loop generated by flatten.
// PRINT-LABEL: void foo8(
// DUMP-LABEL:  FunctionDecl {{.*}} foo8
void foo8() {
  // PRINT:     #pragma omp tile sizes(2)
  // DUMP:      OMPTileDirective
  #pragma omp tile sizes(2)
  // PRINT:     #pragma omp flatten
  // DUMP:      OMPFlattenDirective
  #pragma omp flatten
  for (int i = 0; i < 4; ++i)
    for (int j = 0; j < 3; ++j)
      body(i, j);
}

