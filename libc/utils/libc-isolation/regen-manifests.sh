#!/usr/bin/env bash
# Regenerate the shared-surface manifests from the live header closures.
# Run from the llvm-project root; override the compiler with CXX=.
set -euo pipefail

here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

gen() { # <manifest file> <shared header>...
  local manifest="$1"
  shift
  {
    echo "# Auto-generated by regen-manifests.sh -- do not edit by hand."
    echo "# The libc headers reachable from $*, libc-root-relative."
    bash "$here/shared-closure.sh" "$@"
  } > "$here/$manifest"
  echo "wrote $(grep -vc '^#' "$here/$manifest") entries to $manifest"
}

# Keep in sync with the libc headers compiler-rt/lib/builtins includes.
gen shared-builtins-manifest.txt shared/builtins.h shared/bit.h
gen shared-math-manifest.txt     shared/math.h
