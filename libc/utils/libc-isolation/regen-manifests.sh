#!/usr/bin/env bash
# Regenerate the shared-surface manifests from the live header closures.
# Run from the llvm-project root; override the compiler with CXX=.
set -euo pipefail

here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

gen() { # <umbrella header> <manifest file>
  {
    echo "# Auto-generated by regen-manifests.sh -- do not edit by hand."
    echo "# The libc headers reachable from $1, libc-root-relative."
    bash "$here/shared-closure.sh" "$1"
  } > "$here/$2"
  echo "wrote $(grep -vc '^#' "$here/$2") entries to $2"
}

gen shared/builtins.h shared-builtins-manifest.txt
gen shared/math.h     shared-math-manifest.txt
