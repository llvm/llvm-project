#include "PartitionHelpers.h"
#include "llvm/ADT/STLExtras.h"
#include "llvm/ADT/SmallVectorExtras.h"
#include "llvm/ADT/StringExtras.h"
#include "llvm/ADT/StringMap.h"
#include "llvm/TableGen/Error.h"

using namespace mlir;
using namespace mlir::tblgen;
using llvm::Record;

StringRef mlir::tblgen::getPartitionName(const Record &def) {
  const Record *partition = def.getValueAsOptionalDef("partition");
  return partition ? partition->getValueAsString("partitionName") : "";
}

std::string mlir::tblgen::getPartitionFunctionSuffix(StringRef partition) {
  return llvm::convertToCamelFromSnakeCase(partition, /*capitalizeFirst=*/true);
}

void mlir::tblgen::verifyPartitions(ArrayRef<const Record *> defs,
                                    StringRef selectedPartition, StringRef kind,
                                    StringRef option) {
  bool hasSelectedPartition = false;
  llvm::StringMap<StringRef> partitionsBySuffix;
  for (const Record *def : defs) {
    StringRef partition = getPartitionName(*def);
    // A def without a partition would not be generated by any partition.
    if (partition.empty())
      llvm::PrintFatalError(
          def, kind + " '" + def->getName() + "' is in no partition, but its " +
                   kind + "s are generated by partition with " + option);
    hasSelectedPartition |= partition == selectedPartition;

    std::string suffix = getPartitionFunctionSuffix(partition);
    auto [it, inserted] = partitionsBySuffix.try_emplace(suffix, partition);
    if (!inserted && it->second != partition)
      llvm::PrintFatalError(def, kind + " partitions '" + it->second +
                                     "' and '" + partition +
                                     "' have the same name '" + suffix +
                                     "' in generated functions");
  }
  if (!hasSelectedPartition)
    llvm::PrintFatalError("no " + kind + " is in the specified " + kind +
                          " partition '" + selectedPartition + "'");
}

SmallVector<StringRef>
mlir::tblgen::getPartitionNames(ArrayRef<const Record *> defs) {
  SmallVector<StringRef> partitions = llvm::map_to_vector(
      defs, [](const Record *def) { return getPartitionName(*def); });
  llvm::sort(partitions);
  partitions.erase(llvm::unique(partitions), partitions.end());
  return partitions;
}
