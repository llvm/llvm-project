#ifndef MLIR_TOOLS_MLIRTBLGEN_OPGENHELPERS_H_
#define MLIR_TOOLS_MLIRTBLGEN_OPGENHELPERS_H_

#include "mlir/Support/LLVM.h"
#include "mlir/TableGen/Dialect.h"
#include "llvm/TableGen/Record.h"
#include <string>
#include <vector>

namespace mlir {
namespace tblgen {
/// Returns all the op definitions filtered by the user. The filtering is via
/// command-line options "op-include-regex", "op-exclude-regex" and
/// "op-partition". If `otherPartitionDefs` is non-null, it is set to the op
/// definitions that are only filtered out by "op-partition". Verifies the op
/// partitions if "op-partition" is set.
std::vector<const llvm::Record *> getRequestedOpDefinitions(
    const llvm::RecordKeeper &records,
    std::vector<const llvm::Record *> *otherPartitionDefs = nullptr);

/// Checks whether `str` is a Python keyword or would shadow builtin function.
/// Regenerate using python -c"print(set(sorted(__import__('keyword').kwlist)))"
bool isPythonReserved(llvm::StringRef str);

/// Shard the op definitions into the number of shards set by "op-shard-count".
void shardOpDefinitions(
    ArrayRef<const llvm::Record *> defs,
    SmallVectorImpl<ArrayRef<const llvm::Record *>> &shardedDefs);

/// Returns the op partition set by "op-partition", or an empty string if ops
/// are not generated by partition.
StringRef getSpecifiedOpPartition();

/// Returns the name of the partition of op `def`, or an empty string if the op
/// is in no partition.
StringRef getOpPartitionName(const llvm::Record &def);

/// Returns the name of the function that registers the ops of `dialect` in op
/// partition `partition`, or the ops of all its partitions if `partition` is
/// empty.
std::string getOpRegistrationHookName(const Dialect &dialect,
                                      StringRef partition = "");
} // namespace tblgen
} // namespace mlir

#endif //  MLIR_TOOLS_MLIRTBLGEN_OPGENHELPERS_H_
