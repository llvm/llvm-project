#!/usr/bin/env python3
"""Regenerates SoftF64.inc, the MLIR (LLVM dialect) of soft_f64.c that
arith-emulate-f64 inserts into the modules it emulates double precision in.

  gen_soft_f64.py --clang CLANG --mlir-translate MLIR_TRANSLATE

soft_f64.c only uses 32- and 64-bit integers; the generated functions are
checked for that (no i128, no target-specific intrinsics).
"""

import argparse
import os
import re
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--clang", required=True)
    ap.add_argument("--mlir-translate", required=True)
    a = ap.parse_args()
    with tempfile.TemporaryDirectory() as tmp:
        ll = os.path.join(tmp, "soft.ll")
        subprocess.run([a.clang, "--target=x86_64-unknown-linux-gnu", "-O2", "-fno-vectorize",
                        "-fno-slp-vectorize", "-fno-unroll-loops", "-ffreestanding", "-fno-builtin",
                        "-fno-asynchronous-unwind-tables", "-fno-stack-protector", "-S", "-emit-llvm",
                        os.path.join(HERE, "soft_f64.c"), "-o", ll], check=True)
        ir = open(ll).read()
        code = "\n".join(l for l in ir.splitlines() if not l.startswith("target "))
        bad = set(re.findall(r"\bi128\b|@llvm\.x86\.\w+", code))
        if bad:
            sys.exit("soft_f64.c compiled to IR with " + ", ".join(sorted(bad)))
        # Neither the host's data layout and triple nor its function
        # attributes belong to the library.
        ir = "\n".join(l for l in ir.splitlines() if not l.startswith(("target ", "attributes #")))
        ir = re.sub(r"\) local_unnamed_addr #\d+ \{", ") {", ir)
        ir = re.sub(r"\) #\d+ \{", ") {", ir)
        open(ll, "w").write(ir)
        mlir = os.path.join(tmp, "soft.mlir")
        subprocess.run([a.mlir_translate, "--import-llvm", ll, "-o", mlir], check=True)
        text = open(mlir).read()
    text = re.sub(r"^module attributes \{.*\} \{$", "module {", text, flags=re.M)
    # Loop annotations are aliases defined outside the functions.
    text = re.sub(r"^#loop\w* = .*\n", "", text, flags=re.M)
    text = re.sub(r" \{loop_annotation = #loop_annotation\}| loop_annotation = #loop_annotation", "",
                  text)
    lines = ["// Generated by gen_soft_f64.py from soft_f64.c: do not edit.",
             "static const char *const kSoftF64Library[] = {"]
    for line in text.splitlines():
        lines.append('    "' + line.replace("\\", "\\\\").replace('"', '\\"') + '\\n",')
    lines.append("};")
    open(os.path.join(HERE, "SoftF64.inc"), "w").write("\n".join(lines) + "\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
