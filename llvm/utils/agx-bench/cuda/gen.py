#!/usr/bin/env python3
"""Regenerate ../kernels/cuda_*.ll from the CUDA sources in this directory.

Each NAME.cu is compiled to PTX by clang's NVPTX target (no CUDA toolkit: bench.h declares what the kernels use),
the PTX to AGX LLVM IR by ZLUDA's zoc (its optimized .opt.ll output, as for kernels/matrixmul.ll), and written to
kernels/cuda_NAME.ll with the source's first comment lines: `// agx-cost: ARGS` (the launch agx_cost traces) and a
description. The data files the agx-cost lines map (`--map VA=@data/FILE`) are written to kernels/data/.

  gen.py --zoc ZLUDA/target/debug/zoc [--clang clang] [NAME ...]
"""

import argparse
import glob
import os
import struct
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
KERNELS = os.path.join(HERE, "..", "kernels")


def data_files():
    """CSR row offsets of 4096 rows with 16 and 64 entries each."""
    return {
        "rowptr16.bin": struct.pack("<4097i", *(16 * i for i in range(4097))),
        "rowptr64.bin": struct.pack("<4097i", *(64 * i for i in range(4097))),
    }


def header(src):
    cost, desc = None, []
    for line in open(src):
        if not line.startswith("//"):
            break
        text = line[2:].strip()
        if text.startswith("agx-cost:"):
            cost = text
        else:
            desc.append(text)
    return cost, desc


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--zoc", required=True)
    ap.add_argument("--clang", default="clang")
    ap.add_argument("names", nargs="*")
    a = ap.parse_args()
    os.makedirs(os.path.join(KERNELS, "data"), exist_ok=True)
    for name, data in data_files().items():
        open(os.path.join(KERNELS, "data", name), "wb").write(data)
    sources = [os.path.join(HERE, n + ".cu") for n in a.names] or sorted(glob.glob(os.path.join(HERE, "*.cu")))
    failed = False
    with tempfile.TemporaryDirectory() as tmp:
        for src in sources:
            name = os.path.basename(src)[:-3]
            ptx = os.path.join(tmp, name + ".ptx")
            try:
                subprocess.run([a.clang, "-x", "cuda", "--cuda-device-only", "-nocudainc", "-nocudalib",
                                "--cuda-gpu-arch=sm_80", "-Xclang", "-target-feature", "-Xclang", "+ptx70", "-O3",
                                "-S", src, "-o", ptx], check=True, capture_output=True, text=True)
                subprocess.run([a.zoc, "--arch", "agx-g14c", "--output-dir", tmp, ptx], check=True,
                               capture_output=True, text=True)
            except subprocess.CalledProcessError as e:
                print(f"{name}: {' '.join(e.cmd[:2])} failed:\n{e.stderr}", file=sys.stderr)
                failed = True
                continue
            cost, desc = header(src)
            ir = [l for l in open(os.path.join(tmp, name + ".opt.ll")).read().splitlines(keepends=True)
                  if not l.startswith(("; ModuleID", "source_filename"))]
            with open(os.path.join(KERNELS, "cuda_" + name + ".ll"), "w") as f:
                for d in desc:
                    f.write(f"; {d}\n")
                f.write(f"; Generated by agx-bench/cuda/gen.py from cuda/{name}.cu (clang NVPTX sm_80, zoc --arch "
                        f"agx-g14c .opt.ll).\n")
                if cost:
                    f.write(f"; {cost}\n")
                f.writelines(ir)
            print(f"cuda_{name}.ll")
    sys.exit(1 if failed else 0)


if __name__ == "__main__":
    main()
