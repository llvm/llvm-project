#ifndef LLVM_LIB_TARGET_MSP430_MSP430SUBTARGET_H
#define LLVM_LIB_TARGET_MSP430_MSP430SUBTARGET_H

#include "MSP430FrameLowering.h"
#include "MSP430ISelLowering.h"
#include "MSP430InstrInfo.h"
#include "MSP430RegisterInfo.h"
#include "llvm/CodeGen/TargetSubtargetInfo.h"
#include "llvm/IR/DataLayout.h"
#include <string>

namespace llvm::MSP430 {
enum class HWMult { None, HW16, HW32, F5 };
} // namespace llvm::MSP430

#define OPTIONS_STRUCT_DECL
#include "MSP430Options.inc"

#define GET_SUBTARGETINFO_HEADER
#include "MSP430GenSubtargetInfo.inc"

namespace llvm {
class MSP430TargetMachine;
class StringRef;

class MSP430Subtarget : public MSP430GenSubtargetInfo {
  const MSP430Options &CLOpts;
  virtual void anchor();
  bool ExtendedInsts = false;
  MSP430::HWMult HWMultMode = MSP430::HWMult::None;
  MSP430InstrInfo InstrInfo;
  MSP430TargetLowering TLInfo;
  std::unique_ptr<const SelectionDAGTargetInfo> TSInfo;
  MSP430FrameLowering FrameLowering;

public:
  /// This constructor initializes the data members to match that
  /// of the specified triple.
  ///
  MSP430Subtarget(const Triple &TT, const std::string &CPU,
                  const std::string &FS, const MSP430TargetMachine &TM);

  ~MSP430Subtarget() override;

  const MSP430Options &getCLOpts() const { return CLOpts; }

  MSP430Subtarget &initializeSubtargetDependencies(StringRef CPU, StringRef FS);

  /// ParseSubtargetFeatures - Parses features string setting specified
  /// subtarget options.  Definition of function is auto generated by tblgen.
  void ParseSubtargetFeatures(StringRef CPU, StringRef TuneCPU, StringRef FS);

  bool hasHWMult16() const { return HWMultMode == MSP430::HWMult::HW16; }
  bool hasHWMult32() const { return HWMultMode == MSP430::HWMult::HW32; }
  bool hasHWMultF5() const { return HWMultMode == MSP430::HWMult::F5; }

  bool hasMSP430X() const { return ExtendedInsts; }

  const TargetFrameLowering *getFrameLowering() const override {
    return &FrameLowering;
  }
  const MSP430InstrInfo *getInstrInfo() const override { return &InstrInfo; }
  const MSP430RegisterInfo *getRegisterInfo() const override {
    return &getInstrInfo()->getRegisterInfo();
  }

  const MSP430TargetLowering *getTargetLowering() const override {
    return &TLInfo;
  }

  const SelectionDAGTargetInfo *getSelectionDAGInfo() const override;

  void initLibcallLoweringInfo(LibcallLoweringInfo &Info) const override;
};
} // End llvm namespace

#endif  // LLVM_TARGET_MSP430_SUBTARGET_H
