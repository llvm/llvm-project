#!/usr/bin/env python3
"""Regenerates AIRSoftF64.inc: the LLVM IR of arith-emulate-f64's double
precision library (mlir/lib/Conversion/ArithEmulateF64/SoftF64/soft_f64.c),
which air-emulate-f64 (the AIR target) and agx-raise-to-air (the AGX target)
put in the AIR they write as the emulation of double precision operations.

  gen_air_soft_f64.py --clang CLANG

soft_f64.c only uses 32- and 64-bit integers; the IR is checked for that.
"""

import argparse
import os
import re
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "..", "..", "..", "..", "mlir", "lib", "Conversion", "ArithEmulateF64",
                   "SoftF64", "soft_f64.c")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--clang", required=True)
    a = ap.parse_args()
    with tempfile.TemporaryDirectory() as tmp:
        ll = os.path.join(tmp, "soft.ll")
        subprocess.run([a.clang, "--target=x86_64-unknown-linux-gnu", "-O2", "-fno-vectorize",
                        "-fno-slp-vectorize", "-ffreestanding", "-fno-builtin", "-fno-math-errno",
                        "-fno-asynchronous-unwind-tables", "-fno-stack-protector",
                        "-mllvm", "-phi-node-folding-threshold=1000",
                        "-mllvm", "-two-entry-phi-node-folding-threshold=1000", "-S", "-emit-llvm",
                        SRC, "-o", ll], check=True)
        ir = open(ll).read()
    lines = []
    for l in ir.splitlines():
        if l.startswith(("target ", "source_filename", "; ModuleID", "!")):
            continue
        # metadata attachments (ranges, loop hints): the metadata is dropped
        l = re.sub(r", ![a-z.]+ ![0-9]+", "", l)
        if l.startswith("attributes #"):
            # the host's target attributes mean nothing for AIR
            l = re.sub(r' "(target-cpu|target-features|tune-cpu|stack-protector-buffer-size|'
                       r'min-legal-vector-width)"="[^"]*"', "", l)
        lines.append(l)
    code = "\n".join(lines).strip() + "\n"
    # (the i128 type, not a value named like %add21.i128)
    if re.search(r"(?<![\w.%])i128\b|@llvm\.x86\.\w+", code):
        sys.exit("soft_f64.c compiled to IR with i128 or x86 intrinsics")
    with open(os.path.join(HERE, "AIRSoftF64.inc"), "w") as f:
        f.write("// Generated by gen_air_soft_f64.py from mlir/lib/Conversion/ArithEmulateF64/"
                "SoftF64/soft_f64.c. Do not edit.\n")
        f.write('static const char AIRSoftF64IR[] = R"IR(\n')
        f.write(code)
        f.write(')IR";\n')


if __name__ == "__main__":
    main()
