// Relocs is indexed by relocation type. Check that every entry in Hexagon.def
// has a matching Type and Name at its own index, and that none is missing.
static constexpr bool relocsMatchHexagonDef() {
  constexpr size_t NumRelocs = std::size(Relocs);
  size_t Count = 0;
#define ELF_RELOC(NAME, VALUE)                                                 \
  if ((VALUE) >= NumRelocs || Relocs[VALUE].Type != llvm::ELF::NAME ||         \
      std::string_view(Relocs[VALUE].Name) != #NAME)                           \
    return false;                                                              \
  ++Count;
#include "llvm/BinaryFormat/ELFRelocs/Hexagon.def"
#undef ELF_RELOC
  return Count == NumRelocs;
}
static_assert(relocsMatchHexagonDef(),
              "Relocs is out of sync with ELFRelocs/Hexagon.def");

