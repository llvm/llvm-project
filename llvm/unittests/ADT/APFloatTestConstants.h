// Expected results for APFloat::getConstant, one table per format: the exact
// constant rounded to the format three ways, ordered so that each row reads
// Down <= RNE <= Up.
//
//   Down - toward -inf: the largest value not greater than the constant
//   RNE  - to nearest, ties to even
//   Up   - toward +inf: the smallest value not less than the constant
//
// No constant is exactly representable in these formats, and none lies exactly
// halfway between two representable values, so RNE is unambiguous and
// rmNearestTiesToAway agrees with it.
struct MathConstantRoundings {
  APFloat::MathConstant Constant;
  const char *Name;
  const char *Down;
  const char *RNE;
  const char *Up;
};

